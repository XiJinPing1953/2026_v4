const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm')
const {reactive,ref,computed,watch,nextTick,effectScope}=require('vue')
test('floor panel shows session gross directly across zero, negative readings and restart',async()=>{
 const functions=fs.readFileSync('src/services/pda/floorScaleDisplay.js','utf8').replace(/^export /gm,'')
 const view=fs.readFileSync('src/components/domain/pda/PdaFloorScale.vue','utf8').match(/<script setup>([\s\S]*?)<\/script>/)[1].replace(/^import .*\n/gm,'')
 const props=reactive({active:true,busy:false,snapshot:{is_connected:true,is_online:true,qualified_frame:true,device_id:'A',connection_key:'s1',weight_kg:20,sampled_at:Date.now()}})
 const scope=effectScope()
 const c=scope.run(()=>vm.runInNewContext(functions+'\n'+view+'\n;({weight,showConnection})',{computed,ref,watch,defineProps:()=>props,defineEmits:()=>{}}))
 try {
  assert.equal(c.weight.value,'20.0')
  props.snapshot={...props.snapshot,weight_kg:184.76,display_kg:184.5};await nextTick()
  assert.equal(c.weight.value,'184.5')
  props.snapshot={...props.snapshot,boot_zero_state:'boot_zero_pending',warming:true,qualified_frame:false};await nextTick()
  assert.equal(c.weight.value,'—')
  props.snapshot={...props.snapshot,boot_zero_state:'',warming:false,qualified_frame:true,weight_kg:0,display_kg:0};await nextTick()
  assert.equal(c.weight.value,'0.0')
  props.snapshot={...props.snapshot,connection_key:'s2',weight_kg:-20,display_kg:-20};await nextTick()
  assert.equal(c.weight.value,'-20.0')
  c.showConnection.value=true;props.active=false;await nextTick()
  assert.equal(c.showConnection.value,false)
 } finally {scope.stop()}
})
